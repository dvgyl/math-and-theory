#!/usr/bin/env python3
"""Generate the central all-declaration axiom audit from every root and vendored NYLL Lean module.

Only AxiomAudit.lean is excluded from the audited module inventory. Its imports,
module-name filter, and the Lake library/default-target list are generated from
actual files, so newly added production modules cannot silently miss the audit.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re


MATHLIB_COMMIT = "065356127b1dc0016f66b7283ce0ce2c4055aa55"
MODULE_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*\Z")


def production_modules(project: Path) -> list[str]:
    sources = [path for path in project.glob("*.lean") if path.name != "AxiomAudit.lean"]
    sources.extend((project / "Nyll").rglob("*.lean"))
    modules = sorted(".".join(path.relative_to(project).with_suffix("").parts)
                     for path in sources)
    if not modules:
        raise RuntimeError(f"No production Lean modules in {project}")
    bad = [name for name in modules if not MODULE_NAME.fullmatch(name)]
    if bad:
        raise RuntimeError(f"Unsupported production module names: {bad}")
    return modules


AUDIT_TEMPLATE = '''-- Generated by scripts/generate_audit.py from every root production .lean and Nyll/**/*.lean file.
import Lean.Util.CollectAxioms
__IMPORTS__

/-!
# Transitive axiom audit of every declaration defined by a production module

The environment is traversed directly. No blacklist or public-name heuristic is
used to choose declarations: private helpers, generated declarations, structure
constructors/projections, and unnamed instances are included by defining module.
`Lean.collectAxioms` is the same transitive collector used by `#print axioms`.
JSON records and a checked count summary are consumed by verify_cached.py.
-/

set_option maxHeartbeats 0
set_option maxRecDepth 10000

open Lean Elab Command in
run_cmd do
  let modules : Array Name := #[__MODULE_NAMES__]
  let allowed : Array Name := #[`propext, `Classical.choice, `Quot.sound]
  let env ← getEnv
  for moduleName in modules do
    unless (env.getModuleIdx? moduleName).isSome do
      throwError m!"Production module missing from environment: {moduleName}"
  let declarations ← env.constants.foldM
    (init := (#[] : Array (Name × Name × String))) fun acc name info => do
      match env.getModuleIdxFor? name with
      | none => pure acc
      | some index =>
        let owner := env.header.moduleNames[index.toNat]!
        if modules.contains owner then
          let kind := match info with
            | .axiomInfo _ => "axiom"
            | .defnInfo _ => "definition"
            | .thmInfo _ => "theorem"
            | .opaqueInfo _ => "opaque"
            | .quotInfo _ => "quotient"
            | .inductInfo _ => "inductive"
            | .ctorInfo _ => "constructor"
            | .recInfo _ => "recursor"
          pure (acc.push (owner, name, kind))
        else
          pure acc
  let declarations := declarations.qsort (fun a b => Name.lt a.2.1 b.2.1)
  let mut rejected : Array Name := #[]
  for (owner, name, kind) in declarations do
    let axioms ← collectAxioms name
    let axioms := axioms.qsort Name.lt
    if axioms.any (fun ax => !allowed.contains ax) then
      rejected := rejected.push name
    let record := Json.mkObj [
      ("module", toJson owner.toString),
      ("name", toJson name.toString),
      ("kind", toJson kind),
      ("axioms", toJson (axioms.map Name.toString))]
    logInfo m!"NTC_AXIOM_DECL {record.compress}"
  let mut counts : List (String × Json) := []
  for moduleName in modules do
    let count := (declarations.filter (fun entry => entry.1 == moduleName)).size
    if count == 0 then
      throwError m!"Production module had zero audited declarations: {moduleName}"
    counts := counts ++ [(moduleName.toString, toJson count)]
  let summary := Json.mkObj [
    ("schema", toJson (1 : Nat)),
    ("collector", toJson "Lean.collectAxioms"),
    ("selection", toJson "Environment.getModuleIdxFor? defining module; no name blacklist"),
    ("modules", toJson (modules.map Name.toString)),
    ("counts", Json.mkObj counts),
    ("total", toJson declarations.size),
    ("allowed_axioms", toJson (allowed.map Name.toString))]
  logInfo m!"NTC_AXIOM_SUMMARY {summary.compress}"
  unless rejected.isEmpty do
    throwError m!"Nonstandard transitive axioms in declarations: {rejected.toList}"
'''


def render_audit(modules: list[str]) -> str:
    return (AUDIT_TEMPLATE
            .replace("__IMPORTS__", "\n".join(f"import {name}" for name in modules))
            .replace("__MODULE_NAMES__", ", ".join("`" + name for name in modules)))


def render_lakefile(modules: list[str]) -> str:
    root_modules = [name for name in modules if "." not in name]
    vendor_modules = [name for name in modules if name.startswith("Nyll.")]
    targets = [*root_modules, *(["Nyll"] if vendor_modules else []), "AxiomAudit"]
    header = (
        '# Generated module inventory; use scripts/verify_cached.py for serialized fresh builds.\n'
        'name = "as_depth_research"\n'
        'version = "0.1.0"\n'
        f'defaultTargets = {json.dumps(targets)}\n'
        'moreLeanArgs = ["-j", "1", "-s", "65536"]\n\n'
        '[[require]]\n'
        'name = "mathlib"\n'
        'git = "https://github.com/leanprover-community/mathlib4.git"\n'
        f'rev = "{MATHLIB_COMMIT}"\n'
    )
    libraries = "".join(f'\n[[lean_lib]]\nname = "{name}"\n'
                        for name in [*root_modules, "AxiomAudit"])
    if vendor_modules:
        libraries += '\n[[lean_lib]]\nname = "Nyll"\nroots = ' + json.dumps(vendor_modules) + '\n'
    return header + libraries


def generate(project: Path, *, check: bool = False) -> list[str]:
    modules = production_modules(project)
    artifacts = {
        project / "AxiomAudit.lean": render_audit(modules),
        project / "lakefile.toml": render_lakefile(modules),
    }
    stale = [str(path) for path, content in artifacts.items()
             if not path.is_file() or path.read_text(encoding="utf-8") != content]
    if check and stale:
        raise RuntimeError("Generated audit/module inventory is stale: " + ", ".join(stale))
    if not check:
        for path, content in artifacts.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                path.write_text(content, encoding="utf-8")
    return modules


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true",
                        help="Fail if generated files are stale; do not change them")
    args = parser.parse_args()
    modules = generate(args.project.resolve(), check=args.check)
    print(json.dumps({"production_modules": modules, "count": len(modules),
                      "audit_module": "AxiomAudit", "check_only": args.check}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
