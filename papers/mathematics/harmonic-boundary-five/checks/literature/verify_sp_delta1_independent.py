#!/usr/bin/env python3
"""Independent complete δ=1 SP obstruction checker.

Two-trees are canonized by their properly three-colored triangle/edge
incidence tree, minimized over the six color permutations. This exact
structural code replaces nauty and all graph hashes. All candidates are
generated by ear addition, with the monotone excess bound <=4. Every
feasible edge deletion is checked by fresh bitset BFS and explicit
connectivity after each vertex deletion. No original generator is imported.
"""
from collections import Counter, deque
from pathlib import Path
import argparse
import itertools
import json
import time

COLOR_PERMS = tuple(itertools.permutations('abc'))


def vertices(mask):
    while mask:
        bit = mask & -mask
        yield bit.bit_length()-1
        mask ^= bit


def edges(adj):
    for u, ns in enumerate(adj):
        for v in vertices(ns & ~((1 << (u+1))-1)):
            yield u, v


def decode_graph6(s):
    s = s.strip()
    n = s[0]-63
    assert 0 < n <= 62
    bits = []
    for c in s[1:]:
        z = c-63
        bits.extend((z >> k) & 1 for k in range(5,-1,-1))
    adj = [0]*n
    at = 0
    for v in range(1,n):
        for u in range(v):
            if bits[at]:
                adj[u] |= 1 << v
                adj[v] |= 1 << u
            at += 1
    return tuple(adj)


def encode_graph6(adj):
    n = len(adj)
    bits = [(adj[u] >> v) & 1 for v in range(1,n) for u in range(v)]
    bits += [0]*((-len(bits))%6)
    return chr(n+63)+''.join(chr(63+sum(bits[i+j] << (5-j) for j in range(6)))
                             for i in range(0,len(bits),6))


def unique_coloring(adj):
    n = len(adj)
    alive = (1 << n)-1
    work = list(adj)
    removed = []
    while alive.bit_count() > 3:
        found = None
        for u in vertices(alive):
            ns = work[u] & alive
            if ns.bit_count() == 2:
                a,b = vertices(ns)
                assert (work[a] >> b) & 1
                found = (u,a,b)
                break
        assert found is not None, 'not a two-tree'
        u,a,b = found
        removed.append(found)
        alive ^= 1 << u
    a,b,c = vertices(alive)
    assert all((adj[u] >> v)&1 for u,v in [(a,b),(a,c),(b,c)])
    color = [-1]*n
    color[a],color[b],color[c] = 0,1,2
    for u,a,b in reversed(removed):
        assert color[a] != color[b]
        color[u] = 3-color[a]-color[b]
    assert all(color[u] != color[v] for u,v in edges(adj))
    return tuple(color)


def tree_code(adj, color):
    es = list(edges(adj))
    m = len(es)
    idx = {e:i for i,e in enumerate(es)}
    tree = [[] for _ in range(m)]
    labels = [3-color[u]-color[v] for u,v in es]
    tri_count = 0
    for u,v in es:
        common = adj[u] & adj[v] & ~((1 << (v+1))-1)
        for w in vertices(common):
            z = len(tree)
            ns = [idx[(u,v)],idx[(u,w)],idx[(v,w)]]
            tree.append(ns)
            labels.append(3)
            for a in ns:
                tree[a].append(z)
            tri_count += 1
    assert tri_count == len(adj)-2
    assert sum(map(len,tree)) == 2*(len(tree)-1)
    deg = list(map(len,tree))
    leaves = [u for u,d in enumerate(deg) if d == 1]
    remain = len(tree)
    while remain > 2:
        remain -= len(leaves)
        nxt = []
        for u in leaves:
            deg[u] = 0
            for v in tree[u]:
                if deg[v]:
                    deg[v] -= 1
                    if deg[v] == 1:
                        nxt.append(v)
        leaves = nxt
    assert len(leaves) in (1,2)
    def rooted(u,p,perm):
        label = 't' if labels[u] == 3 else perm[labels[u]]
        return label+'('+''.join(sorted(rooted(v,u,perm) for v in tree[u] if v != p))+')'
    codes = []
    for perm in COLOR_PERMS:
        if len(leaves) == 1:
            codes.append(rooted(leaves[0],-1,perm))
        else:
            a,b = leaves
            codes.append('|'.join(sorted((rooted(a,b,perm),rooted(b,a,perm)))))
    return min(codes)


def connected_avoiding(adj, omit):
    allowed = ((1 << len(adj))-1) & ~(1 << omit)
    if not allowed:
        return True
    seed = allowed & -allowed
    seen = seed
    frontier = seed
    while frontier:
        nxt = 0
        for u in vertices(frontier):
            nxt |= adj[u]
        frontier = nxt & allowed & ~seen
        seen |= frontier
    return seen == allowed


def boundary(adj):
    n = len(adj)
    ds = []
    for s in range(n):
        row = [-1]*n
        row[s] = 0
        seen = 1 << s
        frontier = seen
        level = 0
        while frontier:
            nxt = 0
            for u in vertices(frontier):
                nxt |= adj[u]
            frontier = nxt & ~seen
            seen |= frontier
            level += 1
            for u in vertices(frontier):
                row[u] = level
        assert min(row) == 0
        ds.append(row)
    beta = [max(sum(ds[u][t]-ds[v][t] for v in vertices(adj[u])) for t in range(n))
            for u in range(n)]
    return beta


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--max-order', type=int, default=17)
    p.add_argument('--original-dir', type=Path,
        default=Path(__file__).resolve().parents[1]/'experiments/second_turn')
    p.add_argument('--output', type=Path,
        default=Path(__file__).with_name('sp_delta1_independent_audit.json'))
    args = p.parse_args()
    original = json.loads((args.original_dir/'sp_delta1_certificate.json').read_text())
    front = {tree_code((6,5,3),(0,1,2)): ((6,5,3),(0,1,2))}
    rows = []
    hits = []
    start = time.monotonic()
    for n in range(3,args.max_order+1):
        original_codes = []
        for line in (args.original_dir/f'sp_delta1_completions_n{n}.g6').read_bytes().splitlines():
            adj = decode_graph6(line)
            original_codes.append(tree_code(adj,unique_coloring(adj)))
        assert len(original_codes) == len(set(original_codes))
        assert set(original_codes) == set(front), f'closure mismatch at n={n}'
        following = {}
        deletion_count = 0
        deletion_hist = Counter()
        hit_count = 0
        for adj,color in front.values():
            deg = [x.bit_count() for x in adj]
            excess = sum(max(x-4,0) for x in deg)
            assert excess <= 4
            for u,v in edges(adj):
                if deg[u] > 2 and deg[v] > 2:
                    dg = list(deg)
                    dg[u] -= 1
                    dg[v] -= 1
                    low = sum(x <= 3 for x in dg)
                    slack = sum(x == 3 for x in dg)+sum(max(x-4,0) for x in dg)
                    if low <= 5 and slack <= 2:
                        g = list(adj)
                        g[u] ^= 1 << v
                        g[v] ^= 1 << u
                        if all(connected_avoiding(g,x) for x in range(n)):
                            deletion_count += 1
                            beta = boundary(g)
                            b = sum(x > 0 for x in beta)
                            deletion_hist[b] += 1
                            if b == 5:
                                hits.append({'n':n,'graph6':encode_graph6(g),'beta':beta})
                                hit_count += 1
                if n < args.max_order:
                    new_deg = list(deg)
                    new_deg[u] += 1
                    new_deg[v] += 1
                    if sum(max(x-4,0) for x in new_deg) <= 4:
                        child = list(adj)+[(1 << u)|(1 << v)]
                        child[u] |= 1 << n
                        child[v] |= 1 << n
                        child = tuple(child)
                        cc = color+(3-color[u]-color[v],)
                        code = tree_code(child,cc)
                        following.setdefault(code,(child,cc))
        old = original['counts'][n-3]
        assert len(front) == old['completion_count']
        assert deletion_count == old['raw_degree_feasible_deletions']
        row = {'n':n,'completion_count':len(front),'complete_front_bijection_verified':True,
               'raw_feasible_deletions_checked':deletion_count,
               'raw_boundary_histogram':dict(sorted(deletion_hist.items())),
               'raw_five_boundary_hits':hit_count,
               'elapsed_seconds':round(time.monotonic()-start,3)}
        rows.append(row)
        print(json.dumps(row),flush=True)
        front = following
    # Independent two-case identification at order five.
    types = set()
    for h in hits:
        assert h['n'] == 5
        adj = decode_graph6(h['graph6'].encode())
        high = [u for u,ns in enumerate(adj) if ns.bit_count() == 3]
        assert len(high) == 2
        types.add('house_C5_plus_chord' if ((adj[high[0]] >> high[1])&1) else 'K2_3')
    assert types == {'house_C5_plus_chord','K2_3'}
    report = {'method':'exact unrooted 3-colored triangle-edge incidence-tree codes, all ear additions, own graph6 codec, own BFS and vertex-deletion connectivity',
              'max_order':args.max_order,'all_completion_fronts_match':True,
              'raw_deletions_checked':sum(r['raw_feasible_deletions_checked'] for r in rows),
              'five_boundary_types':sorted(types),'raw_hits':hits,'counts':rows,
              'complete':args.max_order == 17}
    args.output.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({k:v for k,v in report.items() if k not in ('counts','raw_hits')},indent=2))

if __name__ == '__main__':
    main()
